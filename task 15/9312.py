'''	(№ 9312) (Демо-2027) Обозначим через ДЕЛ(n, m) утверждение «натуральное число n делится без остатка на
натуральное число m»; пусть на числовой прямой дан отрезок B = [70; 90]. Для какого наибольшего натурального числа А
логическое выражение
ДЕЛ(х, А) ∨ ((х ∈ В) → ¬ДЕЛ(х, 22))
тождественно истинно, то есть принимает значение 1 при любом натуральном значении переменной х?'''

ans = []
for a in range(1, 1000):
    for x in range(1, 1000):
        if ((x % a == 0) or ((70 <= x <= 90) <= (x % 22 != 0))) == 0:
            break
    else:
        ans.append(a)

print(max(ans))

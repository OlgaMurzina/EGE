'''(№ 7834) На числовой прямой даны три отрезка: P = [192734; 220904], Q = [123456; 1345830], R = [734652; 1023456].
Укажите наименьшую возможную длину такого отрезка A, что формула
(x ∈ Q) → (¬(x ∈ P) → ((¬(x ∈ R) ∧ ¬(x ∈ A)) → ¬(x ∈ Q)))
тождественно истинна, то есть принимает значение 1 при любом значении переменной х?'''

p = (192734, 220904)
q = (123456, 1345830)
r = (734652, 1023456)
otr = sorted(p + q + r)
ans = []
for a1 in otr:
    for a2 in otr:
        if a1 < a2:
            a = (a1, a2)
            for x in range(otr[0] - 2, otr[-1] + 3):
                if ((q[0] <= x <= q[1]) <= ((not(p[0] <= x <= p[1])) <= (((not(r[0] <= x <= r[1])) and (not(a[0] <= x <= a[1]))) <= (not(q[0] <= x <= q[1]))))) == 0:
                    break
            else:
                ans.append((a2 - a1, a))
print(ans)
'''
Найти максимальное значение параметра А:
ДЕЛ(х, 15) -> (-ДЕЛ(х, А) -> -ДЕЛ(х, 60) тождественно истинно при любых х
'''

ans = []
for a in range(1, 1000):
    f = 1
    for x in range(1, 1000):
        if ((x % 15 == 0) <= ((x % a != 0) <= (x % 60 != 0))) == 0:
            f = 0
            break
    if f:
        ans.append(a)
print(ans[-1])
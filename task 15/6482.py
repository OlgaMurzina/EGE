'''(№ 6482) На числовой прямой даны три отрезка: P = [1023; 2148], Q = [1362; 3898] и R = [1813; 2566].
Укажите наименьшую возможную длину такого отрезка A, что формула
(¬((x ∈ Q) → ((x ∈ P) ∨ (x ∈ R)))) → (¬(x ∈ A) → ¬(x ∈ Q))
тождественно истинна, то есть принимает значение 1 при любом значении переменной х?'''

p = (1023, 2148)
q = (1362, 3898)
r = (1813, 2566)
otr = sorted(p + q + r)
ans = []
for a1 in otr:
    for a2 in otr:
        if a1 < a2:
            a = (a1, a2)
            for x in range(otr[0] - 3, otr[-1] + 4):
                if ((not((q[0] <= x <= q[1]) <= ((p[0] <= x <= p[1]) or (r[0] <= x <= r[1])))) <= ((not(a[0] <= x <= a[1])) <= (not(q[0] <= x <= q[1])))) == 0:
                    break
            else:
                ans.append((a2 - a1, a))
print(min(ans))

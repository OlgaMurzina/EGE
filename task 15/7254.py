'''(№ 7254) Обозначим через m & n поразрядную конъюнкцию неотрицательных целых чисел m и n. Например,
14 & 5 = 11102 & 01012 = 01002 = 4. Для какого наименьшего натурального числа А формула
(x & 3582 = 0) → ((x & 4531 ≠ 0) → (x & A ≠ 0))
тождественно истинно (то есть принимает значение 1 при любом натуральном значении переменной X)?'''

ans = []
for a in range(1000, 10000):
    for x in range(1000, 10000):
        if ((x & 3582 == 0) <= ((x & 4531 != 0) <= (x & a != 0))) == 0:
            break
    else:
        ans.append(a)
print(ans)
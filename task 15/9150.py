'''(№ 9150) (ЕГЭ-2026) Для какого наибольшего целого неотрицательного числа А логическое выражение
(x + y ≤ 27) ∨ (y ≤ x − 1) ∨ (y ≥ A)
тождественно истинно (т. е. принимает значение 1) при любых целых положительных x и у?'''

ans = []
for a in range(1000):
    f = 1
    for x in range(1, 1000):
        for y in range(1, 1000):
            if ((x + y <= 27) or (y <= x - 1) or (y >= a)) == 0:
                f = 0
                break
        if f == 0:
            break
    if f:
        ans.append(a)
print(max(ans))

                
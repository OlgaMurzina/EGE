'''(№ 8931) В файле 17-456.txt содержится последовательность целых чисел. Её элементы могут принимать целые
значения от –100 000 до 100 000 включительно. Определите количество троек элементов последовательности,
в которых сумма элементов тройки не меньше минимального положительного элемента последовательности, десятичная
запись которого содержит 68, причём эта сумма совпадает с квадратом натурального числа. В ответе запишите количество
найденных троек, затем максимальную из сумм таких троек. В данной задаче под тройкой подразумеваются три идущих
подряд элемента последовательности.'''

# читаем данные из файла и сразу их переводим в числовой формат (файл лежит рядом с кодом - в одной папке)
data = [int(x) for x in open('17-456.txt').readlines()]
# проверяем, что данные прочитались
print(data)
# находим минимальный положительный элемент последовательности, десятичная запись которого содержит 68
min68 = min([x for x in data if '68' in str(x) and x > 0])
print(min68)
# создаем для удобства проверки список всех квадратов от 1 до 2000
kv = [x ** 2 for x in range(1, 2000)]
print(kv)
# инициализируем счетчик троек
k = 0
# инициализируем максимум для суммы
maxx = -10 ** 20
# идем по индексам - для реализации метода хождения к соседу
for i in range(len(data) - 2):
    # для удобства - берем сразу тройку срезом
    tr = data[i:i+3]
    # проверяем условие - сумма элементов тройки не меньше минимального положительного элемента последовательности, десятичная
    # запись которого содержит 68, причём эта сумма совпадает с квадратом натурального числа
    if sum(tr) >= min68 and sum(tr) in kv:
        # счетчик увеличивается
        k += 1
        # сравниваем сумму с максимальной суммой
        if sum(tr) > maxx:
            maxx = sum(tr)
# выводим ответ
print(k, maxx)


'''(№ 7164) (М. Ишимов) Все 5-буквенные слова, составленные из букв Д, О, Щ, Г, Х, И, М, Т, Э, записаны в алфавитном
порядке и пронумерованы. Вот начало списка:
1. ГГГГГ
2. ГГГГД
3. ГГГГИ
4. ГГГГМ
5. ГГГГО
6. ГГГГТ
...
Сколько существует слов в списке с чётными номерами, которые не начинаются с буквы М или И?'''

from itertools import *

alf = sorted('ДОЩГХИМТЭ')
ans = []
k = 0
for s in product(alf, repeat=5):
    k += 1
    if k % 2 == 0:
        if s[0] not in 'МИ':
            ans.append(s)
print(len(set(ans)))
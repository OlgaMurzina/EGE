'''(№ 9303) (Демо-2027) Все пятибуквенные слова, составленные из букв А, К, Ц, Е, Н, Т, записаны в алфавитном порядке
и пронумерованы. Вот начало списка:
1. ААААА
2. ААААЕ
3. ААААК
4. ААААН
5. ААААТ
6. ААААЦ
...
Определите, под каким номером в этом списке стоит первое слово с чётным номером, которое не начинается с букв
А, Е или К и при этом содержит в своей записи не менее одной буквы Т.'''

from itertools import *

alf = sorted('АКЦЕНТ')
ans = []
k = 0
for s in product(alf, repeat=5):
    k += 1
    if k % 2 == 0:
        if s[0] not in 'АЕК':
            if s.count('Т') >= 1:
                ans.append((k, s))
print(ans[0])
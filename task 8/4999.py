'''(№ 4999) Вася составляет слова из букв слова АКАДЕМИК. Код должен состоять из 8 букв,
и каждая буква в нём должна встречаться столько же раз, сколько в заданном слове. Кроме того,
в коде не должны стоять рядом две гласные и две согласные буквы. Сколько различных слов
может составить Вася?'''

from itertools import *

alf = 'АКАДЕМИК'
gl = 'АЕИ'
sgl = 'КДМК'
ans = []
for s in permutations(alf):
    f = 1
    for i in range(7):
        if (s[i] in gl and s[i + 1] in gl) or (s[i] in sgl and s[i + 1] in sgl):
            f = 0
            break
    if f == 1:
        ans.append(s)
print(len(set(ans)), ans[:10])
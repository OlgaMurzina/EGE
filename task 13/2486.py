'''(№ 2486) Исполнитель Калькулятор преобразует число на экране. У исполнителя есть две команды, которым присвоены номера:
1. Прибавить 1
2. Умножить на 4
Программа для исполнителя Калькулятор – это последовательность команд. Сколько есть программ, которые число 1 преобразуют
в число 32?'''

def f(n):
    if n == 32:
        return 1
    elif n > 32:
        return 0
    else:
        return f(n + 1) + f(4 * n)

print(f(1))
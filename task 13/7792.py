'''(№ 7792) У исполнителя имеются две команды, которые обозначены латинскими буквами:
A. Вычти 2
B. Если число чётное, раздели на 2, иначе вычти 3
Программа для исполнителя – это последовательность команд. Сколько существует программ, которые
преобразуют исходное число 55 в число 3 и при этом траектория вычислений не содержит число 18?'''

def f(n):
    if n == 3:
        return 1
    elif n < 3 or n == 18:
        return 0
    return f(n - 2) + f(n // 2 if n % 2 == 0 else n - 3)

print(f(55))
def f(n):
    if n == 7:
        return 1
    elif n < 7:
        return 0
    else:
        x = de(n)
        return f(n - 1) + f(n // x)

def de(n):
    for d in prime:
        if n % d == 0:
            return d
    return None

def isprime(n):
    for d in range(2, round(n ** 0.5) + 1):
        if n % d == 0:
            return False
    return True


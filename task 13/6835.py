'''(№ 6835) (А. Богданов) У исполнителя Калькулятор имеются три команды, которым присвоены номера:
1. Прибавь 2
2. Умножь на 3
3. Умножь на 5
Выполняя первую из них, исполнитель увеличивает число на экране на 2, выполняя вторую – умножает на 3,
выполняя третью – умножает на 5. Сколько существует программ, для которых при исходном числе 1 результатом
является число 75, и при этом траектория вычислений содержит число 13 и не содержит число 23?'''

def f(n, k13):
    if n == 75 and k13:
        return 1
    elif n >= 75 or n == 23:
        return 0
    elif n == 13:
        k13 = 1
    return f(n + 2, k13) + f(n * 3, k13) + f(n * 5, k13)

print(f(1, 0))
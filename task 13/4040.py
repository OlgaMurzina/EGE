'''(№ 4040) Исполнитель Калькулятор преобразует число, записанное на экране. У исполнителя есть две команды, которым
присвоены номера:
1. Прибавь 1
2. Умножь на 2 и вычти 3
Сколько различных результатов можно получить из исходного числа 3 после выполнения программы,
содержащей ровно 12 команд?'''

def f(n, k):
    if k == 12:
        ans.add(n)
        return 0
    elif k > 12:
        return 0
    return f(n + 1, k + 1) + f(2 * n - 3,  k + 1)

ans = set()
f(3, 0)
print(len(ans))

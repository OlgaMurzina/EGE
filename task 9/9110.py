"""(№ 9110) (ЕГЭ-2026) В файле электронной таблицы 9-290.ods в каждой строке записаны шесть натуральных чисел.
Определите количество строк таблицы, для которых выполнены оба условия:
– в строке есть ровно два числа, каждое из которых повторяется дважды, остальные числа различны;
– сумма всех повторяющихся чисел строки больше суммы всех её неповторяющихся чисел.
В ответе запишите только число.
"""

t1 = open('9-290.csv').readlines()
print(t1[:5])
t = []
for s in t1:
    t.append(list(map(int, s.split(';'))))
print(t[:5])

ans = []
for s in t:
    dv = list(filter(lambda x: s.count(x) == 2, s))
    un = list(filter(lambda x: s.count(x) == 1, s))
    if len(dv) == 4 and len(un) == 2:
        if sum(dv) > sum(un):
            ans.append(s)
print(len(ans))
"""(№ 8728) (Д. Нечаев) В файле электронной таблицы 9-268.ods в каждой строке записаны семь целых чисел.
Определите минимальную сумму чисел строки среди всех строк, для которых выполнено хотя бы одно, но не все три из следующих условий:
– сумма чётных чисел в строке меньше суммы нечётных чисел;
– количество чисел в строке, делящихся на 3, меньше количества чисел, делящихся на 5;
– среднее арифметическое чисел в строке не меньше разности максимального и минимального значений.
В ответе запишите абсолютное значение наименьшей суммы."""

t1 = open('9-268.csv').readlines()
print(t1[:5])
t = []
for s in t1:
    t.append(list(map(int, s.split(';'))))
print(t[:5])

ans = []
for s in t:
    edd = [x for x in s if x % 2 == 0]
    odd = [x for x in s if x % 2]
    n3 = [x for x in s if x % 3 == 0]
    n5 = [x for x in s if x % 5 == 0]
    con =  [sum(edd) < sum(odd), len(n3) < len(n5), sum(s) / 7 >= max(s) - min(s)]
    if 1 <= con.count(1) <= 2:
        ans.append(sum(s))
print(abs(min(ans)))
"""(№ 7354) В файле электронной таблицы 9-228.xls в каждой строке записаны шесть натуральных чисел.
Назовём ячейку таблицы интересной, если выполняются следующие условия:
– число в данной ячейке больше не встречается в данной строке;
– число в данной ячейке встречается в данном столбце, включая данную ячейку, менее 170 раз.
Определите количество строк в таблице, содержащих более четырёх интересных ячеек. В ответе запишите только число."""

t1 = open('9-228.csv').readlines()
print(t1[:5])
t = []
for s in t1:
    t.append(list(map(int, s.split(';'))))
print(t[:5])
t_tr = []
for j in range(len(t[0])):
    s = []
    for i in range(len(t)):
        s.append(t[i][j])
    t_tr.append(s)
print(t_tr[:1][:100])

ans = []
for s in t:
    k = 0
    for x in s:
        if s.count(x) == 1:
            if t_tr[s.index(x)].count(x) < 170:
                k += 1
    if k > 4:
        ans.append(s)
print(len(ans))

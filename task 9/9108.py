'''(№ 9108) (ЕГЭ-2026) В файле электронной таблицы 9-288.ods в каждой строке записаны пять натуральных чисел.
Определите сумму чисел в строке таблицы с наименьшим номером, содержащей числа, для которых выполнены оба условия:
– в строке все числа различны;
– удвоенная сумма максимального и минимального чисел строки больше суммы оставшихся трёх её чисел.
В ответе запишите только число.'''

data1 = open('9-288.csv').readlines()
print(data1[:5])
data = []
for st in data1:
    data.append([int(x) for x in st.split()])
print(data[:5])

for st in data:
    s = sorted(st)
    if len(st) == len(set(st)):
        if 2 * (s[0] + s [-1]) > sum(s[1:-1]):
            print(sum(st))
            break
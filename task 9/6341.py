"""(№ 6341) *В файле электронной таблицы 9-204.xls в каждой строке записаны 6 неотрицательных целых чисел.
Определите количество строк таблицы, содержащих хотя бы одну ячейку со следующими свойствами:
– число в данной ячейке повторяется в ячейках этой строки;
– число в данной ячейке встречается нечётное число раз в других строках таблицы."""

t1 = open('9-204.csv').readlines()
print(t1[:5])
t = []
tt = []
for s in t1:
    t.append(list(map(int, s.split(';'))))
    tt.extend(list(map(int, s.split(';'))))
print(t[:5])
print(tt[:15])

ans = []
for s in t:
    for x in s:
        if s.count(x) > 1:
            if (tt.count(x) - s.count(x)) % 2:
                ans.append(s)
                break
print(len(ans))


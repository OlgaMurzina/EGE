'''(№ 8935) **(А. Сражаев) Напишите программу, которая перебирает целые числа, превышающие 2 480 000, которые
единственным образом можно представить в виде суммы a**3 + b**5, где a и b – два различных натуральных числа, каждое
из которых содержит цифру 9 в своей записи. В ответе запишите в первом столбце первые 5 найденных чисел в порядке
возрастания, а во втором столбце — сумму чисел a и b.'''

from datetime import datetime
t1 = datetime.now()
num9 = [x for x in range(9, 200) if '9' in str(x)]
ans = set()
for a in num9:
    for b in num9:
        if a != b:
            x = a ** 3 + b ** 5
            if x > 2_480_000:
                ans.add((x, a + b))
ans = sorted(ans)
print(*ans[:5], sep='\n')
t2 = datetime.now()
print(t2 - t1)
'''(№ 8841) Среди девятизначных натуральных чисел найдите пять наибольших чисел, которые можно представить
в виде суммы некоторого натурального числа, кратного 1063, и суммы различных нетривиальных натуральных
делителей этого числа. В ответе запишите все найденные числа в порядке возрастания, справа от каждого
числа запишите сумму его нетривиальных делителей.'''

def good(x):
    de = set()
    for d in range(2, round(x ** 0.5) + 1):
        if x % d == 0:
            de.add(d)
            de.add(x // d)
    if de:
        return sum(de)
    return 0

ans = []
for x in range(999_999_999, 99_999_999, -1):
    y = good(x)
    if y and y < x:
        if (x - y) % 1063 == 0:
            ans.append((x, y))
    if len(ans) == 5:
        break
for x, y in sorted(ans):
    print(x, y)

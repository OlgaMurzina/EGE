'''Черепаха выполнила следующую программу:
Налево 255
Повтори 3 [Налево 30 Повтори 4 [Вперёд 10 Налево 90]]
Определите, общее количество различных точек с целочисленными координатами,
которые будут находиться на пересечении только двух фигур, полученных при
выполнении данной программы. Точки на линиях учитывать не следует.'''

from turtle import *
tracer(0)
k=30
lt(90)
screensize(1000,1000)
lt(255)
for i in range(3):
    lt(30)
    for j in range(4):
        fd(10*k)
        lt(90)
up()
for x in range(-100,100):
    for y in range(-100,100):
        goto(x*k,y*k)
        dot(3,'red')
done()
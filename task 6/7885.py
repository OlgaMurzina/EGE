'''(№ 7885) В начальный момент на поле находятся две Черепахи. Первая Черепаха находится в начале координат
и направлена вверх (вдоль положительного направления оси ординат). Вторая Черепаха находится в неизвестной точке поля
и направлена вправо (вдоль положительного направления оси абсцисс). Каждая Черепаха выполнила следующую программу:
Повтори 2 [Вперёд 15 Направо 90 Вперёд 19 Направо 90]
Определите максимально возможное количество точек с целочисленными координатами, которые могут оказаться внутри
пересечения фигур, нарисованных двумя Черепахами. Точки, находящиеся на линиях, учитывать не следует.'''

from turtle import *

m = 20
lt(90)
for i in range(2):
    fd(15 * m)
    rt(90)
    fd(19 * m)
    rt(90)
fd(15 * m)
rt(90)
for i in range(2):
    fd(15 * m)
    rt(90)
    fd(19 * m)
    rt(90)
up()
tracer(100)
k = 0
for x in range(1, 15):
    for y in range(1, 15):
        goto(x * m, y * m)
        dot(5, 'blue')
        k += 1
print(k)
done()


'''Исполнитель преобразует число, записанное на экране. У исполнителя есть четыре команды которые обозначены латинскими
буквами:
A. Прибавить 1
B. Прибавить 2
С. Прибавить 4
D. Прибавить 8
Программа исполнителя — это последовательность команд.
Сколько существует программ, для которых при исходном числе 16 результатом является число 48, если никакую из
команд нельзя повторять дважды подряд?'''

def f(n, a, b, c, d):
    if n == 48:
        return 1
    elif n > 48:
        return 0
    if a:
        a = 0
        return f(n + 2, a, 1, c, d) + f(n + 4, a, b, 1, d) + f(n + 8, a, b, c, 1)
    elif b:
        b = 0
        return f(n + 1, 1, b, c, d) + f(n + 4, a, b, 1, d) + f(n + 8, a, b, c, 1)
    elif c:
        c = 0
        return f(n + 1, 1, b, c, d) + f(n + 2, a, 1, c, d) + f(n + 8, a, b, c, 1)
    elif d:
        d = 0
        return f(n + 1, 1, b, c, d) + f(n + 2, a, 1, c, d) + f(n + 4, a, b, 1, d)
    else:
        return f(n + 1, 1, b, c, d) + f(n + 2, a, 1, c, d) + f(n + 4, a, b, 1, d) + f(n + 8, a, b, c, 1)

print(f(16, 0, 0, 0, 0))


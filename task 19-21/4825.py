for s in range(1, 43):
    if f(s, 0, 0, [3]) == 1:
        print('20)', s)

# 21
for s in range(1, 43):
    if f(s, 0, 0, [2, 4]) == 1 and f(s, 0, 0, [2]) == 0:
        print('21)', s)